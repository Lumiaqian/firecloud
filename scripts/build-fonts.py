"""Regenerate runtime Xiaolai shards: uv run --with 'fonttools[woff]==4.61.1' scripts/build-fonts.py."""
from pathlib import Path
from io import BytesIO
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'designs/sky-letter-system/project/fonts/Xiaolai-Regular.woff2'
OUT = ROOT / 'assets/fonts'
original = TTFont(SOURCE)
# Decode WOFF2 once, rather than repeating Brotli work for every shard.
sfnt = BytesIO()
original.flavor = None
original.save(sfnt)
source_bytes = sfnt.getvalue()
coverage = set(original.getBestCmap())
# Include every shipped UI character; dynamic city names load additional shards.
text = (ROOT / 'index.html').read_text()
for path in sorted((ROOT / 'js').rglob('*.mjs')):
    text += path.read_text()
core = (set(map(ord, text)) | set(range(0x20, 0x100))) & coverage
remaining = sorted(coverage - core)
groups = [('core', sorted(core))] + [(f'{i // 512:03}', remaining[i:i + 512]) for i in range(0, len(remaining), 512)]
css = ['/* Generated by scripts/build-fonts.py; complete source cmap coverage. */']
verified = set()
for name, points in groups:
    font = TTFont(BytesIO(source_bytes))
    options = subset.Options()
    options.layout_features = ['*']
    options.recalc_timestamp = False
    worker = subset.Subsetter(options=options)
    worker.populate(unicodes=points)
    worker.subset(font)
    target = OUT / f'Xiaolai-{name}.woff2'
    font.flavor = 'woff2'
    font.save(target)
    actual = set(TTFont(target).getBestCmap())
    assert actual == set(points), name
    assert not (verified & actual), name
    verified |= actual
    ranges = []
    for point in points:
        if ranges and point == ranges[-1][1] + 1:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])
    unicode_range = ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in ranges)
    css.append('@font-face {\n  font-family: "Xiaolai";\n'
               f'  src: url("../assets/fonts/{target.name}") format("woff2");\n'
               '  font-weight: 400;\n  font-style: normal;\n  font-display: swap;\n'
               f'  unicode-range: {unicode_range};\n}}')
assert verified == coverage
(ROOT / 'css/fonts.css').write_text('\n'.join(css) + '\n')
expected_files = {f'Xiaolai-{name}.woff2' for name, _ in groups}
for stale in OUT.glob('Xiaolai-*.woff2'):
    if stale.name not in expected_files:
        stale.unlink()
print(f'{len(groups)} shards; {len(verified)} codepoints verified; core { (OUT / "Xiaolai-core.woff2").stat().st_size } bytes; source {SOURCE.stat().st_size} bytes')
